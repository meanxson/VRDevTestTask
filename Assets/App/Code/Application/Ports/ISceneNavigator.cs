namespace App.Application.Ports
{
    /// <summary>
    /// Переходы между сценами приложения. Прикладной слой оперирует смыслом
    /// ("лобби", "тренировка"), а не именами сцен и не SceneManager.
    /// </summary>
    public interface ISceneNavigator
    {
        /// <summary>Загрузить лобби.</summary>
        void LoadLobby();

        /// <summary>
        /// Загрузить сцену тренировки. Повторный вызов перезагружает её —
        /// именно так работает кнопка "Попытаться ещё": сцена возвращается
        /// в исходное состояние вместе со всеми перемещёнными объектами.
        /// </summary>
        void LoadTraining();
    }
}
