using App.Domain.Scenarios;

namespace App.Application.Ports
{
    /// <summary>
    /// Источник описания сценария. Прикладной слой знает только то, что сценарий
    /// откуда-то приходит; откуда именно — из JSON, из ScriptableObject или из сети —
    /// решает инфраструктура.
    /// </summary>
    public interface IScenarioSource
    {
        /// <summary>
        /// Загрузить сценарий. Реализация обязана бросить исключение с внятным
        /// текстом, если конфигурация повреждена: прикладной слой превратит его
        /// в сообщение для пользователя.
        /// </summary>
        Scenario Load();
    }
}
