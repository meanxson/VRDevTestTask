namespace App.Application.Composition
{
    /// <summary>
    /// Компонент сцены, которому нужны зависимости приложения.
    ///
    /// Unity создаёт компоненты сама, поэтому передать им зависимости через
    /// конструктор нельзя. Вместо глобальной точки доступа, из которой компоненты
    /// сами бы всё вытягивали, зависимости им отдаёт композиционный корень —
    /// один раз, сразу после загрузки сцены. Зависимость при этом видна в сигнатуре,
    /// а не прячется внутри метода, и в тесте её можно подставить руками.
    /// </summary>
    public interface IAppDependent
    {
        /// <summary>
        /// Получить собранное приложение. Вызывается корнем до первого Start
        /// компонентов сцены.
        /// </summary>
        void Construct(AppComposition app);
    }
}
