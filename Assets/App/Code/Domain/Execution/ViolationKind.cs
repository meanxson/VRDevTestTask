namespace App.Domain.Execution
{
    /// <summary>
    /// Вид нарушения. Конкретика ("подошёл не туда", "кликнул не на тот объект",
    /// "нажал не ту кнопку") восстанавливается из типа действия пользователя,
    /// поэтому домену достаточно различать две принципиально разные ситуации.
    /// </summary>
    public enum ViolationKind
    {
        /// <summary>Действие совершено не над той целью, которую ждёт текущий шаг.</summary>
        WrongTarget = 0,

        /// <summary>
        /// Выполнено действие более позднего шага текущей группы —
        /// нарушение линейной последовательности.
        /// </summary>
        WrongOrder = 1
    }
}
